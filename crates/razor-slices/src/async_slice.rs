/// A minimal, runtime-agnostic async byte sink used by streaming rendering.
///
/// This is the Rust equivalent of upstream's `PipeWriter` / `TextWriter`
/// destination for `RenderAsync`. Implementors adapt whatever writer their
/// async runtime or framework exposes (see the `tokio` feature's
/// `TokioWriter` for a ready-made `tokio::io::AsyncWrite` adapter).
///
/// Methods return `impl Future<..> + Send` (rather than using `async fn`
/// sugar directly) so the returned futures are `Send`, which multi-threaded
/// async executors (including tokio's default one, used by the axum
/// integration in #6) require in order to spawn/await them across threads.
pub trait AsyncSliceWriter {
    /// Writes all of `buf` to the sink.
    fn write_all(&mut self, buf: &[u8])
        -> impl std::future::Future<Output = io::Result<()>> + Send;

    /// Flushes any buffered data.
    ///
    /// This is the equivalent of upstream's mid-template `FlushAsync()`,
    /// used by the streaming sample to push partially-rendered output to the
    /// client before the rest of the template has finished rendering.
    /// [`AsyncSlice`] implementations call this through
    /// [`AsyncHtmlWriter::flush`]; generated [`crate::async_template!`] bodies
    /// can use the explicit `@flush;` directive.
    fn flush(&mut self) -> impl std::future::Future<Output = io::Result<()>> + Send;
}

/// An error that occurred while rendering a slice asynchronously.
#[derive(Debug)]
pub enum AsyncRenderError {
    /// Rendering the template body failed.
    Render(RenderError),
    /// Writing (or flushing) to the destination writer failed.
    Write(io::Error),
}

impl std::fmt::Display for AsyncRenderError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AsyncRenderError::Render(e) => write!(f, "error rendering slice: {e}"),
            AsyncRenderError::Write(e) => write!(f, "error writing rendered slice: {e}"),
        }
    }
}

impl std::error::Error for AsyncRenderError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            AsyncRenderError::Render(e) => Some(e),
            AsyncRenderError::Write(e) => Some(e),
        }
    }
}

impl From<RenderError> for AsyncRenderError {
    fn from(value: RenderError) -> Self {
        AsyncRenderError::Render(value)
    }
}

impl From<io::Error> for AsyncRenderError {
    fn from(value: io::Error) -> Self {
        AsyncRenderError::Write(value)
    }
}

/// Renders `slice` and streams the result to `writer`.
///
/// This is a bridge/adapter for today's synchronous [`Slice`] implementations
/// (hand-written, or generated by #3 before it supports `@await`): it renders
/// to an in-memory buffer via [`Slice::render_to_bytes`] exactly as the sync
/// path does, then performs a single `write_all` + `flush` to `writer`. It
/// lets any existing `Slice` be used wherever a streaming destination (e.g.
/// an HTTP response body) is expected today, without waiting on template
/// codegen to support genuine incremental, mid-template streaming.
///
/// For true incremental execution and mid-template flushes, implement
/// [`AsyncSlice`] (or declare one with [`crate::async_template!`]) and use
/// [`render_incremental`]. This function retains the
/// fully buffered behavior for existing synchronous slices.
pub async fn render_async(
    slice: &(impl Slice + ?Sized),
    writer: &mut impl AsyncSliceWriter,
) -> Result<(), AsyncRenderError> {
    let bytes = slice.render_to_bytes()?;
    writer.write_all(&bytes).await?;
    writer.flush().await?;
    Ok(())
}

#[cfg(feature = "tokio")]
mod tokio_adapter {
    use super::AsyncSliceWriter;
    use std::io;
    use tokio::io::{AsyncWrite, AsyncWriteExt};

    /// An [`AsyncSliceWriter`] adapter over any `tokio::io::AsyncWrite`.
    ///
    /// Available behind the default-off `tokio` Cargo feature.
    ///
    /// ```
    /// # #[tokio::main(flavor = "current_thread")]
    /// # async fn main() -> Result<(), Box<dyn std::error::Error>> {
    /// use razor_slices::{render_async, Slice, TokioWriter};
    /// use std::fmt;
    ///
    /// struct Hello;
    /// impl Slice for Hello {
    ///     fn render(&self, writer: &mut dyn fmt::Write) -> fmt::Result {
    ///         writer.write_str("<p>Hello, World!</p>")
    ///     }
    /// }
    ///
    /// let mut buf = Vec::new();
    /// let mut writer = TokioWriter::new(&mut buf);
    /// render_async(&Hello, &mut writer).await?;
    /// assert_eq!(buf, b"<p>Hello, World!</p>");
    /// # Ok(())
    /// # }
    /// ```
    pub struct TokioWriter<W>(W);

    impl<W: AsyncWrite + Unpin> TokioWriter<W> {
        /// Wraps `inner` so it can be used as an [`AsyncSliceWriter`].
        pub fn new(inner: W) -> Self {
            TokioWriter(inner)
        }

        /// Unwraps the adapter, returning the inner writer.
        pub fn into_inner(self) -> W {
            self.0
        }
    }

    impl<W: AsyncWrite + Unpin + Send> AsyncSliceWriter for TokioWriter<W> {
        async fn write_all(&mut self, buf: &[u8]) -> io::Result<()> {
            AsyncWriteExt::write_all(&mut self.0, buf).await
        }

        async fn flush(&mut self) -> io::Result<()> {
            AsyncWriteExt::flush(&mut self.0).await
        }
    }
}

